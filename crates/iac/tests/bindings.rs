use crucible_iac::bindings::{Build, bindings, declaration, declares_handles};
use crucible_iac::lock::Lock;
use crucible_iac::model::{Experience, Problem};
use crucible_project::Manifest;

const CONFIG: &str = r#"
[places.start]
project = "default.project.json"

[env.staging]
universe = 10772177432
place = 132306245523809

[products.coin-pack]
name = "Coin pack"
price = 49

[products.old-pack]
retired = true

[passes.vip]
name = "VIP"
price = 299

[passes.legacy]
name = "Legacy"
untrack = true

[badges.first-delivery]
name = "First delivery"
"#;

const LOCK: &str = r#"
version = 1

[env.staging]
universe = 10772177432

[env.staging.products.coin-pack]
id = 3301234567
fingerprint = "sha256:a"
status = "managed"

[env.staging.passes.vip]
id = 4401234567
fingerprint = "sha256:b"
status = "managed"

[env.staging.passes.legacy]
id = 4401234568
fingerprint = "sha256:c"
status = "managed"

[env.staging.badges.first-delivery]
id = 2124000000000000
fingerprint = "sha256:d"
status = "managed"
"#;

fn experience(config: &str) -> (Manifest, Experience) {
    let manifest = Manifest::parse(config).unwrap();
    let experience = Experience::new(&manifest).unwrap();
    (manifest, experience)
}

fn staging(config: &str, lock: &str) -> Result<String, Vec<Problem>> {
    let (manifest, experience) = experience(config);
    let lock = Lock::parse(lock).unwrap();
    bindings(&experience, Build::Env { name: "staging", env: &manifest.envs["staging"], lock: lock.env("staging") })
}

#[test]
fn the_declaration_types_a_handle_for_each_key_but_an_untracked_one_and_holds_no_id() {
    let (_, experience) = experience(CONFIG);
    assert_eq!(
        declaration(&experience),
        r#"// Generated by crucible build from crucible.toml. Do not edit it: the next build rewrites it.

declare module "crucible:experience" {
	import type { BadgeHandle, PassHandle, ProductHandle } from "@trioforge/crucible";

	export const Products: {
		readonly CoinPack: ProductHandle<"coin-pack">;
		readonly OldPack: ProductHandle<"old-pack">;
	};

	export const Passes: {
		readonly Vip: PassHandle<"vip">;
	};

	export const Badges: {
		readonly FirstDelivery: BadgeHandle<"first-delivery">;
	};
}
"#
    );
    assert!(declares_handles(&experience));
}

#[test]
fn a_kind_with_no_key_declares_an_empty_object() {
    let (_, experience) = experience("[places.start]\nproject = \"p.json\"\n\n[badges.a]\nname = \"A\"\n");
    let text = declaration(&experience);
    assert!(text.contains("\texport const Products: {};\n"), "{text}");
    assert!(text.contains("\texport const Passes: {};\n"), "{text}");
}

#[test]
fn an_environment_s_bindings_hold_the_ids_of_its_lock() {
    let source = staging(CONFIG, LOCK).unwrap();
    assert!(source.starts_with("-- crucible:experience for the environment staging, generated by crucible build.\n"));
    for line in [
        "\t\tCoinPack = bound(\"coin-pack\", 3301234567),\n",
        "\t\tOldPack = unbound(\"old-pack\", \"retired product old-pack has no Roblox ID in crucible.lock for staging\"),\n",
        "\t\tVip = bound(\"vip\", 4401234567),\n",
        "\t\tFirstDelivery = bound(\"first-delivery\", 2124000000000000),\n",
    ] {
        assert!(source.contains(line), "{line:?} in\n{source}");
    }
    assert!(!source.contains("Legacy") && !source.contains("4401234568"), "an untracked key has no handle");
}

#[test]
fn a_build_without_an_environment_binds_no_id() {
    let (_, experience) = experience(CONFIG);
    let source = bindings(&experience, Build::Unbound).unwrap();
    assert!(source.starts_with("-- crucible:experience for no environment"));
    assert!(
        source.contains(
            "\t\tCoinPack = unbound(\"coin-pack\", \"product coin-pack has no Roblox ID in this place, because crucible \
             build ran without --env. Build with crucible build --env <environment>\"),\n"
        ),
        "{source}"
    );
    assert!(!source.contains("= bound("), "{source}");
}

#[test]
fn a_managed_key_without_an_id_fails_an_environment_s_build_and_names_provision() {
    let lock = LOCK.replace("[env.staging.passes.vip]\nid = 4401234567", "[env.staging.passes.unrelated]\nid = 1");
    let problems = staging(CONFIG, &lock).unwrap_err();
    assert_eq!(
        problems.iter().map(ToString::to_string).collect::<Vec<_>>(),
        ["crucible.toml:16: passes.vip: crucible.lock holds no ID for it in staging, so a build for staging cannot \
          bind Passes.Vip. Run crucible provision staging, commit crucible.lock, and build again"]
    );
    let (manifest, experience) = experience(CONFIG);
    let missing = bindings(&experience, Build::Env { name: "staging", env: &manifest.envs["staging"], lock: None });
    assert_eq!(missing.unwrap_err().len(), 3, "with no lock, each managed key is missing");
}

#[test]
fn a_lock_for_another_universe_binds_nothing() {
    let problems = staging(CONFIG, &LOCK.replace("universe = 10772177432", "universe = 1")).unwrap_err();
    assert_eq!(problems.len(), 1);
    assert!(problems[0].message.starts_with("crucible.lock records staging's resources in universe 1"), "{problems:?}");
}
