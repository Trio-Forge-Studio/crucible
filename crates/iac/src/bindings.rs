//! What game code imports from `crucible:experience`. The declaration types one handle for each declared product, pass
//! and badge and holds no ID, so it is the same in every environment. The bindings are the Luau module a build puts in
//! the place, with the IDs `crucible.lock` records for the environment it builds for.

use crate::lock::EnvLock;
use crate::model::{Experience, Fields, Kind, Lifecycle, Problem, Resource, handle};
use crucible_project::Env;

/// The specifier game code imports the handles from.
pub const SPECIFIER: &str = "crucible:experience";
/// The declaration's path from the project root. TypeScript's `include` globs skip folders that start with a dot, so it
/// lives under `src`, which every game's tsconfig includes.
pub const DECLARATION: &str = "src/crucible-experience.d.ts";

/// The environment a build binds the handles to.
#[derive(Clone, Copy, Debug)]
pub enum Build<'a> {
    /// A build for no environment. Each handle throws when its ID is read.
    Unbound,
    Env {
        name: &'a str,
        env: &'a Env,
        lock: Option<&'a EnvLock>,
    },
}

/// The keys game code reaches: every declared key but an untracked one, whose ID crucible no longer records.
fn handles(experience: &Experience, kind: Kind) -> impl Iterator<Item = &Resource> {
    experience.resources().filter(move |resource| resource.kind == kind && resource.lifecycle != Lifecycle::Untrack)
}

pub fn declares_handles(experience: &Experience) -> bool {
    Kind::ALL.into_iter().any(|kind| handles(experience, kind).next().is_some())
}

/// A retired product has its own type, because CRU039 lets a place leave it ungranted.
fn handle_type(resource: &Resource) -> &'static str {
    match resource.kind {
        Kind::Product if resource.lifecycle == Lifecycle::Retired => "RetiredProductHandle",
        Kind::Product => "ProductHandle",
        Kind::Pass => "PassHandle",
        Kind::Badge => "BadgeHandle",
    }
}

pub fn declaration(experience: &Experience) -> String {
    let mut text = format!(
        "// Generated by crucible build from crucible.toml. Do not edit it: the next build rewrites it.\n\ndeclare \
         module \"{SPECIFIER}\" {{\n\timport type {{ BadgeHandle, PassHandle, ProductHandle, \
         RetiredProductHandle }} from \"@trioforge/crucible\";\n"
    );
    for kind in Kind::ALL {
        let members: Vec<_> = handles(experience, kind).collect();
        // Lint rules such as no-empty-object-type reject `{}`, and the file is committed.
        if members.is_empty() {
            text += &format!("\n\texport const {}: Record<never, never>;\n", kind.handles());
            continue;
        }
        text += &format!("\n\texport const {}: {{\n", kind.handles());
        for resource in members {
            text +=
                &format!("\t\treadonly {}: {}<\"{}\">;\n", handle(&resource.key), handle_type(resource), resource.key);
        }
        text += "\t};\n";
    }
    text + "}\n"
}

/// The bindings' Luau for `build`. A build for an environment fails when the lock holds no ID for a managed key,
/// because a place that cannot sell a product must not reach players. A retired key without an ID never existed there,
/// so its handle is absent: its `id` throws when read, and a grant of it claims nothing, since no receipt can name it.
/// A product's or a pass's `forSale` is false when it is retired or the environment's overlay keeps it off sale.
pub fn bindings(experience: &Experience, build: Build<'_>) -> Result<String, Vec<Problem>> {
    if let Build::Env { name, env, lock: Some(lock) } = build
        && lock.universe() != env.universe
    {
        return Err(vec![crate::plan::another_universe(name, lock, env.universe)]);
    }
    let mut problems = Vec::new();
    let mut text = format!("-- {SPECIFIER} ");
    text += &match build {
        Build::Unbound => "for no environment".to_owned(),
        Build::Env { name, .. } => format!("for the environment {name}"),
    };
    text += ", generated by crucible build.\n";
    text += BINDING_FUNCTIONS;
    text += "\nreturn table.freeze({\n";
    let resolved = match build {
        Build::Unbound => vec![],
        Build::Env { env, .. } => experience.resolve(env),
    };
    for kind in Kind::ALL {
        text += &format!("\t{} = table.freeze({{\n", kind.handles());
        for resource in handles(experience, kind) {
            let key = &resource.key;
            let noun = kind.noun();
            let fields = resolved.iter().find(|other| other.kind == kind && other.key == *key);
            let on_sale = resource.lifecycle == Lifecycle::Managed
                && fields.and_then(|resource| resource.fields.as_ref()).is_none_or(Fields::on);
            let for_sale = if kind == Kind::Badge { String::new() } else { format!(", {on_sale}") };
            let value = match build {
                Build::Unbound => unbound(
                    key,
                    &format!(
                        "{noun} {key} has no Roblox ID in this place, because crucible build ran without --env. Build \
                         with crucible build --env <environment>"
                    ),
                ),
                Build::Env { name, lock, .. } => {
                    match lock.and_then(|lock| lock.entries(kind).get(key)).map(|entry| entry.id) {
                        Some(id) => format!("bound({key:?}, {id}{for_sale})"),
                        None if resource.lifecycle == Lifecycle::Managed => {
                            problems.push(Problem::at(
                                resource.line,
                                format!("{}.{key}", kind.table()),
                                format!(
                                    "crucible.lock holds no ID for it in {name}, so a build for {name} cannot bind \
                                     {}. Run crucible provision {name}, commit crucible.lock, and build again",
                                    resource.handle()
                                ),
                            ));
                            continue;
                        }
                        None => {
                            let message = format!("retired {noun} {key} has no Roblox ID in crucible.lock for {name}");
                            format!("absent({key:?}, {message:?}{for_sale})")
                        }
                    }
                }
            };
            text += &format!("\t\t{} = {value},\n", handle(key));
        }
        text += "\t}),\n";
    }
    text += "})\n";
    if problems.is_empty() { Ok(text) } else { Err(problems) }
}

fn unbound(key: &str, message: &str) -> String {
    format!("unbound({key:?}, {message:?})")
}

const BINDING_FUNCTIONS: &str = r#"
local function bound(key: string, id: number, forSale: boolean?)
	return table.freeze({ key = key, id = id, forSale = forSale })
end

local function missing(handle, message: string)
	return table.freeze(setmetatable(handle, {
		__index = function(_, field)
			if field == "id" or field == "forSale" then
				error(message, 2)
			end
			return nil
		end,
	}))
end

local function unbound(key: string, message: string)
	return missing({ key = key }, message)
end

local function absent(key: string, message: string, forSale: boolean?)
	return missing({ key = key, absent = true, forSale = forSale }, message)
end
"#;
