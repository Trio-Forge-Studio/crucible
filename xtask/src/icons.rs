use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};

use flate2::{Compression, GzBuilder};

const SOURCE: &str = "crates/cli/lucide.json.gz";
const NAMES: &str = "packages/crucible/src/ui/lucide.d.ts";

pub fn main(args: &[String]) -> Result<(), String> {
    let check = match args.first().map(String::as_str) {
        None | Some("generate") if args.len() <= 1 => false,
        Some("check") if args.len() == 1 => true,
        _ => return Err("usage: cargo xtask icons [generate|check]".into()),
    };
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..");
    let package = root.join("packages/crucible/node_modules/lucide-static");
    let manifest: serde_json::Value = json(&package.join("package.json"))?;
    let version = manifest["version"].as_str().ok_or("lucide-static has no version")?;
    // The SVG directory includes deprecated aliases. These are the canonical names.
    let nodes: BTreeMap<String, serde_json::Value> = json(&package.join("icon-nodes.json"))?;
    if nodes.is_empty() {
        return Err("lucide-static lists no icons".into());
    }
    let mut icons = BTreeMap::new();
    for name in nodes.keys() {
        let path = package.join("icons").join(format!("{name}.svg"));
        let svg = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?.replace("\r\n", "\n");
        icons.insert(name, svg);
    }
    let mut encoder = GzBuilder::new().operating_system(255).write(Vec::new(), Compression::best());
    encoder
        .write_all(&serde_json::to_vec(&(version, icons)).expect("the SVGs serialize"))
        .map_err(|e| e.to_string())?;
    generated(&root, SOURCE, &encoder.finish().map_err(|e| e.to_string())?, check)?;

    let mut names = String::from("// Generated by cargo xtask icons.\nexport type IconName =\n");
    let mut keys = nodes.keys().peekable();
    while let Some(name) = keys.next() {
        let end = if keys.peek().is_none() { ";" } else { "" };
        writeln!(names, "\t| {name:?}{end}").expect("writing to a string succeeds");
    }
    generated(&root, NAMES, names.as_bytes(), check)
}

fn json<T: serde::de::DeserializeOwned>(path: &Path) -> Result<T, String> {
    let bytes = fs::read(path).map_err(|e| format!("{}: {e}. Run `pnpm install`.", path.display()))?;
    serde_json::from_slice(&bytes).map_err(|e| format!("{}: {e}", path.display()))
}

fn generated(root: &Path, path: &str, bytes: &[u8], check: bool) -> Result<(), String> {
    if check {
        if fs::read(root.join(path)).ok().as_deref() != Some(bytes) {
            return Err(format!("{path} is stale. Run `cargo xtask icons generate`."));
        }
        Ok(())
    } else {
        fs::write(root.join(path), bytes).map_err(|e| format!("{path}: {e}"))
    }
}
